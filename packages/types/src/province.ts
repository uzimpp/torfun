export const ThaiProvince = z.enum(THAI_PROVINCES);
export type ThaiProvince = z.infer<typeof ThaiProvince>;

/**
 * The words that place a record in a province when they occur in its agency or
 * project name (FR-29). e-GP publishes no location field, so this is a keyword
 * match, not a verified address. "เลย" and "ตาก" are also everyday words or part
 * of district names (ตากใบ), so for them only the "จังหวัด"/"จ." forms count.
 */
export function provinceTerms(province: ThaiProvince): string[] {
  if (province === 'กรุงเทพมหานคร') return ['กรุงเทพมหานคร', 'กรุงเทพฯ', 'กทม'];
  if (province === 'เลย' || province === 'ตาก') return [`จังหวัด${province}`, `จ.${province}`];
  return [province];
}
